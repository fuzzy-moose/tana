-- Times are TIMESTAMPTZ; NULL means unset.

-- Feeds

CREATE TABLE raw_feeds (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    captured_at TIMESTAMPTZ NOT NULL,
    feed_url TEXT NOT NULL,
    body BYTEA NOT NULL,
    processed_at TIMESTAMPTZ,
    last_attempt_at TIMESTAMPTZ,
    last_error TEXT
);
CREATE INDEX raw_feeds_capture_order ON raw_feeds (captured_at, id);
CREATE INDEX raw_feeds_pending ON raw_feeds (captured_at, id) WHERE processed_at IS NULL;

CREATE TABLE gallery_refs (
    gallery_id BIGINT PRIMARY KEY CHECK (gallery_id > 0),
    token TEXT NOT NULL CHECK (length(token) > 0),
    metadata_attempted_at TIMESTAMPTZ,
    metadata_error TEXT,
    metadata_priority INTEGER NOT NULL DEFAULT 0,
    feed_metadata_base_at TIMESTAMPTZ
);
CREATE INDEX gallery_refs_pending_metadata ON gallery_refs (metadata_priority, gallery_id)
WHERE metadata_attempted_at IS NULL;
-- Diagnostics must not scan successful collection history to find ten errors.
CREATE INDEX gallery_refs_recent_metadata_errors
ON gallery_refs (metadata_attempted_at DESC NULLS LAST, gallery_id)
WHERE metadata_error IS NOT NULL AND metadata_error != '';

CREATE TABLE feed_continuity_checks (
    previous_capture_id BIGINT NOT NULL REFERENCES raw_feeds (id),
    current_capture_id BIGINT NOT NULL REFERENCES raw_feeds (id),
    status TEXT NOT NULL CHECK (status IN ('unknown', 'overlap', 'possible_gap')),
    created_at TIMESTAMPTZ NOT NULL,
    checked_at TIMESTAMPTZ NOT NULL,
    PRIMARY KEY (previous_capture_id, current_capture_id),
    CHECK (previous_capture_id != current_capture_id)
);
CREATE INDEX feed_continuity_checks_current ON feed_continuity_checks (current_capture_id);

-- Capture timestamps and sightings still establish scheduling and continuity
-- after processed feed bodies are cleared.
CREATE TABLE feed_gallery_refs (
    raw_feed_id BIGINT NOT NULL REFERENCES raw_feeds (id),
    gallery_id BIGINT NOT NULL REFERENCES gallery_refs (gallery_id),
    PRIMARY KEY (raw_feed_id, gallery_id)
);
CREATE INDEX feed_gallery_refs_gallery ON feed_gallery_refs (gallery_id);

