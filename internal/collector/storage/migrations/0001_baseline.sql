CREATE TABLE catalog_galleries (
    gallery_id BIGINT PRIMARY KEY REFERENCES gallery_refs (gallery_id) ON DELETE CASCADE,
    title TEXT NOT NULL,
    title_lower TEXT NOT NULL,
    title_japanese_lower TEXT NOT NULL,
    thumbnail_url TEXT NOT NULL,
    page_count INTEGER,
    posted TIMESTAMPTZ,
    ordered_at TIMESTAMPTZ NOT NULL,
    -- NULL while only provisional feed metadata is known.
