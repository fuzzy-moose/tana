WHERE status IN ('processing', 'validating');

-- Outcomes belong to each import. Completing or retrying one owner must not
-- rewrite another owner's terminal outcome for the same reference.
CREATE TABLE reference_import_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    import_id TEXT NOT NULL REFERENCES reference_imports (id) ON DELETE CASCADE,
    gallery_id BIGINT NOT NULL,
    token TEXT NOT NULL,
    status TEXT NOT NULL CHECK (status IN ('pending', 'known', 'imported', 'failed', 'cancelled')),
    UNIQUE (import_id, gallery_id, token)
);
CREATE INDEX reference_import_entries_pending_ref ON reference_import_entries (gallery_id, token)
WHERE status = 'pending';
CREATE INDEX reference_import_entries_pending_order ON reference_import_entries (import_id, id)
WHERE status = 'pending';
-- Claims skip galleries already reserved by other metadata workers. Checking
-- older tokens must seek within one gallery, even when many proxies reserve
-- a long prefix of the pending import.
CREATE INDEX reference_import_entries_pending_gallery
ON reference_import_entries (import_id, gallery_id, id) WHERE status = 'pending';
CREATE INDEX reference_import_entries_outcomes ON reference_import_entries (import_id, status);

-- Summary reads stay constant-sized even for imports with hundreds of thousands
-- of entries; counters commit in the same transaction as their outcomes.
CREATE FUNCTION reference_import_entry_insert() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    UPDATE reference_imports SET
        reference_count = reference_count + 1,
        known = known + (NEW.status = 'known')::int,
        imported = imported + (NEW.status = 'imported')::int,
        failed = failed + (NEW.status = 'failed')::int,
        pending = pending + (NEW.status = 'pending')::int,
        cancelled = cancelled + (NEW.status = 'cancelled')::int
    WHERE id = NEW.import_id;
    RETURN NULL;
END;
$$;
CREATE TRIGGER reference_import_entry_insert AFTER INSERT ON reference_import_entries
FOR EACH ROW EXECUTE FUNCTION reference_import_entry_insert();

CREATE FUNCTION reference_import_entry_outcome() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    UPDATE reference_imports SET
        known = known + (NEW.status = 'known')::int - (OLD.status = 'known')::int,
        imported = imported + (NEW.status = 'imported')::int - (OLD.status = 'imported')::int,
        failed = failed + (NEW.status = 'failed')::int - (OLD.status = 'failed')::int,
        pending = pending + (NEW.status = 'pending')::int - (OLD.status = 'pending')::int,
        cancelled = cancelled + (NEW.status = 'cancelled')::int - (OLD.status = 'cancelled')::int
    WHERE id = NEW.import_id;
    RETURN NULL;
END;
$$;
CREATE TRIGGER reference_import_entry_outcome AFTER UPDATE OF status ON reference_import_entries
FOR EACH ROW WHEN (OLD.status != NEW.status) EXECUTE FUNCTION reference_import_entry_outcome();

-- Resumable inventory check over entries with after_entry_id < id <= through_entry_id.
CREATE TABLE reference_import_reconciliation (
    id INTEGER PRIMARY KEY CHECK (id = 1),
    after_entry_id BIGINT NOT NULL,
    through_entry_id BIGINT NOT NULL
);
INSERT INTO reference_import_reconciliation (id, after_entry_id, through_entry_id) VALUES (1, 0, 0);

CREATE TABLE reference_import_inventory_queue (
    sequence BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gallery_id BIGINT NOT NULL UNIQUE REFERENCES gallery_refs (gallery_id)
);

-- Every inventory writer participates without doing import updates in its
-- transaction. The pending-reference index makes the existence check bounded.
CREATE FUNCTION reference_import_inventory_insert() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF EXISTS (SELECT 1 FROM reference_import_entries WHERE gallery_id = NEW.gallery_id AND status = 'pending') THEN
        INSERT INTO reference_import_inventory_queue (gallery_id) VALUES (NEW.gallery_id)
        ON CONFLICT (gallery_id) DO NOTHING;
    END IF;
    RETURN NULL;
END;
$$;
CREATE TRIGGER reference_import_inventory_insert AFTER INSERT ON gallery_refs
FOR EACH ROW EXECUTE FUNCTION reference_import_inventory_insert();

