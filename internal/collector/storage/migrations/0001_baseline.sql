    metadata_source TEXT NOT NULL DEFAULT 'collected' CHECK (metadata_source IN ('feed', 'collected')),
    first_seen_at TIMESTAMPTZ,
    feed_captured_at TIMESTAMPTZ,
    feed_capture_id BIGINT,
    uploader TEXT NOT NULL DEFAULT '',
    description TEXT NOT NULL DEFAULT ''
);
CREATE INDEX catalog_posted ON catalog_galleries (ordered_at DESC, gallery_id DESC);
CREATE INDEX catalog_visible_posted ON catalog_galleries (ordered_at DESC, gallery_id DESC)
WHERE expunged IS DISTINCT FROM true;
-- Visibility trails the ordering keys to preserve upload order when expunged galleries are included.
CREATE INDEX catalog_category_posted ON catalog_galleries (category, ordered_at DESC, gallery_id DESC, expunged);

CREATE TABLE catalog_gallery_tags (
    gallery_id BIGINT NOT NULL REFERENCES catalog_galleries (gallery_id) ON DELETE CASCADE,
    tag_id BIGINT NOT NULL REFERENCES catalog_tags (id),
    PRIMARY KEY (gallery_id, tag_id)
);
CREATE INDEX catalog_tag_galleries ON catalog_gallery_tags (tag_id, gallery_id);

CREATE FUNCTION catalog_collected_metadata_deleted() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    DELETE FROM catalog_galleries WHERE gallery_id = OLD.gallery_id AND metadata_source = 'collected';
    RETURN NULL;
END;
$$;
CREATE TRIGGER catalog_collected_metadata_deleted AFTER DELETE ON gallery_metadata
FOR EACH ROW EXECUTE FUNCTION catalog_collected_metadata_deleted();

