-- Times are TIMESTAMPTZ; NULL means unset.

-- Catalog

CREATE TABLE libraries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL CHECK (length(trim(name)) > 0),
    path TEXT UNIQUE NOT NULL,
    availability TEXT NOT NULL DEFAULT 'unknown'
        CHECK (availability IN ('unknown', 'available', 'unavailable')),
    last_checked_at TIMESTAMPTZ
);

CREATE TABLE sources (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    library_id BIGINT NOT NULL REFERENCES libraries (id) ON DELETE CASCADE,
    path TEXT NOT NULL CHECK (length(path) > 0),
    kind TEXT NOT NULL CHECK (kind IN ('directory', 'archive')),
    CONSTRAINT sources_library_path UNIQUE (library_id, path)
);

CREATE TABLE source_files (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id BIGINT NOT NULL REFERENCES sources (id) ON DELETE CASCADE,
    path TEXT NOT NULL CHECK (length(path) > 0),
    UNIQUE (source_id, path)
);

CREATE TABLE galleries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL CHECK (length(trim(title)) > 0),
    source_id BIGINT REFERENCES sources (id) ON DELETE CASCADE
);
CREATE INDEX galleries_source ON galleries (source_id);
CREATE INDEX galleries_title ON galleries (lower(title), id);

-- Position preserves order; page numbers are its consecutive ranks. Cascading
-- deletions can leave gaps in independent galleries without renumbering writes.
CREATE TABLE gallery_pages (
    gallery_id BIGINT NOT NULL REFERENCES galleries (id) ON DELETE CASCADE,
    position INTEGER NOT NULL CHECK (position > 0),
    source_file_id BIGINT NOT NULL REFERENCES source_files (id) ON DELETE CASCADE,
    PRIMARY KEY (gallery_id, position)
);
CREATE INDEX gallery_pages_source_file ON gallery_pages (source_file_id);

CREATE TABLE namespaces (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT UNIQUE NOT NULL CHECK (
        length(name) > 0 AND name = trim(name) AND name !~ '[^a-z]'
    )
);

CREATE TABLE tags (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    namespace_id BIGINT NOT NULL REFERENCES namespaces (id),
    value TEXT NOT NULL CHECK (
        length(value) > 0 AND value = trim(value) AND value !~ '[^a-z0-9 .-]'
    ),
    UNIQUE (namespace_id, value)
);

CREATE TABLE gallery_tags (
    gallery_id BIGINT NOT NULL REFERENCES galleries (id) ON DELETE CASCADE,
    tag_id BIGINT NOT NULL REFERENCES tags (id),
    PRIMARY KEY (gallery_id, tag_id)
);
CREATE INDEX gallery_tags_tag ON gallery_tags (tag_id, gallery_id);

-- Panda

-- A NULL next_attempt_at is due immediately.
CREATE TABLE panda_enrichments (
    gallery_id BIGINT PRIMARY KEY REFERENCES galleries (id) ON DELETE CASCADE,
    panda_id BIGINT NOT NULL CHECK (panda_id > 0),
    next_attempt_at TIMESTAMPTZ,
    failures INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX panda_enrichments_due ON panda_enrichments (next_attempt_at NULLS FIRST, gallery_id);

CREATE TABLE panda_deliveries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    state TEXT NOT NULL CHECK (state IN ('running', 'paused', 'stopped', 'completed', 'completed_with_errors')),
    data JSONB NOT NULL
);
CREATE UNIQUE INDEX panda_deliveries_active ON panda_deliveries ((true))
WHERE state IN ('running', 'paused');

-- A NULL next_cleanup is due immediately.
CREATE TABLE panda_delivery_items (
    delivery_id BIGINT NOT NULL REFERENCES panda_deliveries (id) ON DELETE CASCADE,
    position INTEGER NOT NULL,
    gallery_id BIGINT NOT NULL,
    state TEXT NOT NULL,
    cleanup_attempts INTEGER NOT NULL,
    next_cleanup TIMESTAMPTZ,
    data JSONB NOT NULL,
    PRIMARY KEY (delivery_id, position),
    UNIQUE (delivery_id, gallery_id)
);
CREATE INDEX panda_delivery_items_unfinished ON panda_delivery_items (delivery_id, position)
WHERE state IN ('queued', 'transferring', 'transferred', 'saved', 'importing');
CREATE INDEX panda_delivery_items_state ON panda_delivery_items (delivery_id, state);
CREATE INDEX panda_delivery_items_cleanup ON panda_delivery_items (state, cleanup_attempts, next_cleanup NULLS FIRST);

CREATE TABLE panda_catalog_default_filter (
    id INTEGER PRIMARY KEY CHECK (id = 1),
    query TEXT NOT NULL,
    categories JSONB NOT NULL
);
