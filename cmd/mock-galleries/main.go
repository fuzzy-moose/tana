// Command mock-galleries gives the local development instance a fresh set of
// mock galleries for the design cases of the gallery page.
//
// Start the development server first:
//
//	go run ./cmd/tana --dev
//
// Then run this command from the repository:
//
//	go run ./cmd/mock-galleries
//	go run ./cmd/mock-galleries --count 40 --server http://127.0.0.1:8080
//
// The command writes the galleries to test-galleries/ at the repository root.
// Then it registers the folder as the library "Mock galleries" and scans it
// through the HTTP API of the server. Each run replaces the folder and the
// mock library. The reading progress of mock galleries is lost. The command
// uses a fixed seed, so each run gives the same galleries.
//
// The command does not replace a test-galleries/ folder that it did not make.
// Source names do not end with a bracketed number, so the server does not
// replace mock metadata with data from a collector.
package main

import (
	"context"
	"errors"
	"flag"
	"fmt"
	"os"
	"os/signal"
	"path/filepath"
	"syscall"
	"time"
)

const (
	outputName  = "test-galleries"
	markerName  = ".tana-generated-fixtures"
	libraryName = "Mock galleries"
)

func main() {
	count := flag.Int("count", 120, "number of galleries")
	server := flag.String("server", "http://127.0.0.1:8080", "base URL of the running Tana server")
	flag.Parse()
	if flag.NArg() != 0 || *count < 1 {
		flag.Usage()
		os.Exit(2)
	}
	ctx, stop := signal.NotifyContext(context.Background(), syscall.SIGINT, syscall.SIGTERM)
	defer stop()
	if err := run(ctx, *count, *server); err != nil {
		fmt.Fprintln(os.Stderr, "mock-galleries:", err)
		os.Exit(1)
	}
}

func run(ctx context.Context, count int, server string) error {
	root, err := repositoryRoot()
	if err != nil {
		return err
	}
	output := filepath.Join(root, outputName)
	if err := checkReplaceable(output); err != nil {
		return err
	}
	api := newClient(server)
	// Fail before generation when the server is not running.
	if _, err := api.libraries(ctx); err != nil {
		return fmt.Errorf("%w\nstart the server with: go run ./cmd/tana --dev", err)
	}

	started := time.Now()
	pages, err := generateInto(ctx, root, output, count)
	if err != nil {
		return err
	}
	fmt.Printf("Generated %d galleries with %d pages in %s\nLibrary root: %s\n", count, pages, time.Since(started).Round(time.Millisecond), output)

	return setUpLibrary(ctx, api, output)
}

// repositoryRoot finds the nearest parent directory of the working directory
// that holds go.mod.
func repositoryRoot() (string, error) {
	dir, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", errors.New("run the command inside the Tana repository")
		}
		dir = parent
	}
}

func checkReplaceable(output string) error {
	info, err := os.Lstat(output)
	if errors.Is(err, os.ErrNotExist) {
		return nil
	}
	if err != nil {
		return err
	}
	if !info.IsDir() {
		return fmt.Errorf("refusing to replace %s: not a generated library", output)
	}
	if _, err := os.Stat(filepath.Join(output, markerName)); err != nil {
		return fmt.Errorf("refusing to replace %s: not a generated library", output)
	}
	return nil
}

// generateInto stages the library next to output, so the previous galleries
// stay intact on failure and the final rename stays on one filesystem.
func generateInto(ctx context.Context, root, output string, count int) (int, error) {
	stage, err := os.MkdirTemp(root, ".tana-fixtures-")
	if err != nil {
		return 0, err
	}
	defer os.RemoveAll(stage)
	library := filepath.Join(stage, "library")
	if err := os.Mkdir(library, 0o755); err != nil {
		return 0, err
	}
	pages, err := generate(ctx, library, count)
	if err != nil {
		return 0, fmt.Errorf("generate galleries: %w", err)
	}
	if err := os.WriteFile(filepath.Join(library, markerName), []byte("Generated by cmd/mock-galleries\n"), 0o644); err != nil {
		return 0, err
	}
	if err := os.RemoveAll(output); err != nil {
		return 0, err
	}
	return pages, os.Rename(library, output)
}

func setUpLibrary(ctx context.Context, api *client, root string) error {
	libraries, err := api.libraries(ctx)
	if err != nil {
		return err
	}
	for _, l := range libraries {
		if l.Path == root {
			if err := api.deleteLibrary(ctx, l.ID); err != nil {
				return fmt.Errorf("delete library %d: %w", l.ID, err)
			}
			fmt.Printf("Deleted library %d (%s)\n", l.ID, l.Name)
		}
	}
	created, err := api.createLibrary(ctx, libraryName, root)
	if err != nil {
		return fmt.Errorf("create library: %w", err)
	}
	fmt.Printf("Created library %d (%s)\n", created.ID, created.Name)
	if err := api.requestScan(ctx, created.ID); err != nil {
		return fmt.Errorf("request scan: %w", err)
	}
	status, err := api.waitForScan(ctx)
	if err != nil {
		return err
	}
	fmt.Printf("Scan %s: %d discovered, %d imported, %d failed, %d galleries created\n",
		status.Phase, status.Discovered, status.Imported, status.FailedSources, status.GalleriesCreated)
	if status.Phase != "completed" {
		return fmt.Errorf("scan ended with phase %s; see the server log", status.Phase)
	}
	return nil
}
